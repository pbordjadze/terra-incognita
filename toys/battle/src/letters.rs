//! Engraved capitals: a single-stroke letter for each capital, digit and the few marks the page's words
//! use, drawn as polylines on a grid four wide and six tall (y down, the baseline at 6), so the page can
//! carry a print's lettering in its own ink: how to begin before the first order, the day's outcome
//! after it (painting-company row 216). Letters not here are left as a space.

type Glyph = &'static [&'static [(f32, f32)]];

fn glyph(c: char) -> Glyph {
    match c {
        'A' => &[&[(0., 6.), (2., 0.), (4., 6.)], &[(0.8, 3.8), (3.2, 3.8)]],
        'B' => &[&[(0., 6.), (0., 0.), (3., 0.), (4., 0.8), (4., 2.2), (3., 3.), (0., 3.)], &[(3., 3.), (4., 3.8), (4., 5.2), (3., 6.), (0., 6.)]],
        'C' => &[&[(4., 1.), (3., 0.), (1., 0.), (0., 1.), (0., 5.), (1., 6.), (3., 6.), (4., 5.)]],
        'D' => &[&[(0., 0.), (0., 6.), (2.5, 6.), (4., 4.5), (4., 1.5), (2.5, 0.), (0., 0.)]],
        'E' => &[&[(4., 0.), (0., 0.), (0., 6.), (4., 6.)], &[(0., 3.), (3., 3.)]],
        'F' => &[&[(4., 0.), (0., 0.), (0., 6.)], &[(0., 3.), (3., 3.)]],
        'G' => &[&[(4., 1.), (3., 0.), (1., 0.), (0., 1.), (0., 5.), (1., 6.), (3., 6.), (4., 5.), (4., 3.5), (2.2, 3.5)]],
        'H' => &[&[(0., 0.), (0., 6.)], &[(4., 0.), (4., 6.)], &[(0., 3.), (4., 3.)]],
        'I' => &[&[(2., 0.), (2., 6.)], &[(1., 0.), (3., 0.)], &[(1., 6.), (3., 6.)]],
        'J' => &[&[(4., 0.), (4., 5.), (3., 6.), (1., 6.), (0., 5.)]],
        'K' => &[&[(0., 0.), (0., 6.)], &[(4., 0.), (0., 3.6)], &[(1.4, 2.4), (4., 6.)]],
        'L' => &[&[(0., 0.), (0., 6.), (4., 6.)]],
        'M' => &[&[(0., 6.), (0., 0.), (2., 4.), (4., 0.), (4., 6.)]],
        'N' => &[&[(0., 6.), (0., 0.), (4., 6.), (4., 0.)]],
        'O' | '0' => &[&[(1., 0.), (3., 0.), (4., 1.), (4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.)]],
        'P' => &[&[(0., 6.), (0., 0.), (3., 0.), (4., 0.8), (4., 2.4), (3., 3.2), (0., 3.2)]],
        'Q' => &[&[(1., 0.), (3., 0.), (4., 1.), (4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.)], &[(2.5, 4.5), (4., 6.4)]],
        'R' => &[&[(0., 6.), (0., 0.), (3., 0.), (4., 0.8), (4., 2.4), (3., 3.2), (0., 3.2)], &[(2., 3.2), (4., 6.)]],
        'S' => &[&[(4., 1.), (3., 0.), (1., 0.), (0., 1.), (0., 2.), (1., 3.), (3., 3.), (4., 4.), (4., 5.), (3., 6.), (1., 6.), (0., 5.)]],
        'T' => &[&[(0., 0.), (4., 0.)], &[(2., 0.), (2., 6.)]],
        'U' => &[&[(0., 0.), (0., 5.), (1., 6.), (3., 6.), (4., 5.), (4., 0.)]],
        'V' => &[&[(0., 0.), (2., 6.), (4., 0.)]],
        'W' => &[&[(0., 0.), (1., 6.), (2., 2.5), (3., 6.), (4., 0.)]],
        'X' => &[&[(0., 0.), (4., 6.)], &[(4., 0.), (0., 6.)]],
        'Y' => &[&[(0., 0.), (2., 3.), (4., 0.)], &[(2., 3.), (2., 6.)]],
        'Z' => &[&[(0., 0.), (4., 0.), (0., 6.), (4., 6.)]],
        '1' => &[&[(1., 1.), (2., 0.), (2., 6.)], &[(1., 6.), (3., 6.)]],
        '2' => &[&[(0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 2.), (0., 6.), (4., 6.)]],
        '3' => &[&[(0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 2.), (3., 3.), (1.5, 3.)], &[(3., 3.), (4., 4.), (4., 5.), (3., 6.), (1., 6.), (0., 5.)]],
        '4' => &[&[(3., 6.), (3., 0.), (0., 4.), (4., 4.)]],
        '5' => &[&[(4., 0.), (0., 0.), (0., 3.), (3., 3.), (4., 4.), (4., 5.), (3., 6.), (0., 6.)]],
        '6' => &[&[(3.5, 0.), (1., 0.), (0., 1.), (0., 5.), (1., 6.), (3., 6.), (4., 5.), (4., 4.), (3., 3.), (0., 3.)]],
        '7' => &[&[(0., 0.), (4., 0.), (1.5, 6.)]],
        '8' => &[&[(1., 3.), (0., 2.), (0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 2.), (3., 3.), (1., 3.), (0., 4.), (0., 5.), (1., 6.), (3., 6.), (4., 5.), (4., 4.), (3., 3.)]],
        '9' => &[&[(4., 3.), (1., 3.), (0., 2.), (0., 1.), (1., 0.), (3., 0.), (4., 1.), (4., 5.), (3., 6.), (0.5, 6.)]],
        '.' => &[&[(2., 5.7), (2., 6.)]],
        ',' => &[&[(2., 5.6), (1.5, 7.)]],
        ':' => &[&[(2., 1.7), (2., 2.)], &[(2., 5.7), (2., 6.)]],
        '\'' => &[&[(2., 0.), (2., 1.6)]],
        '-' => &[&[(1., 3.), (3., 3.)]],
        _ => &[],
    }
}

/// Advance of a letter and of a space, in grid units.
const ADV: f32 = 5.8;
const SPACE: f32 = 4.0;

/// How wide `text` runs, in grid units.
pub fn width(text: &str) -> f32 {
    let mut w = 0.0;
    for c in text.chars() {
        w += if c == ' ' { SPACE } else { ADV };
    }
    (w - (ADV - 4.0)).max(0.0)
}

/// The polylines of `text` set with its first letter's top left at `at` and `scale` units a grid step.
pub fn lines(text: &str, at: [f32; 2], scale: f32) -> Vec<Vec<[f32; 2]>> {
    let mut out = vec![];
    let mut x = at[0];
    for c in text.chars() {
        if c == ' ' {
            x += SPACE * scale;
            continue;
        }
        for pl in glyph(c.to_ascii_uppercase()) {
            out.push(pl.iter().map(|&(gx, gy)| [x + gx * scale, at[1] + gy * scale]).collect());
        }
        x += ADV * scale;
    }
    out
}
