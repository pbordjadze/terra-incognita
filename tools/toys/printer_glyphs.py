"""The line printer's type for Huddle's printout (toys/huddle/src/printer.wgsl), as WGSL constants.

    python3 tools/toys/printer_glyphs.py > toys/huddle/src/printer_type.wgsl

Kitty (Koshechka, Moscow State University, 1968) was printed on the BESM-4's ACPU-128, a drum printer
with whole type, as "numerical patterns" (toys/huddle/SOURCES.md). Here the digits and a few marks are
cut from DejaVu Sans Mono Bold at W x H, four bits a pixel, eight pixels a u32, and sorted by how much ink
each puts down, lightest first: `TYPE` holds the bitmaps, `INK` each one's share of its cell.
"""

from PIL import Image, ImageDraw, ImageFont

W, H = 12, 20
CHARS = ".-:+=17432569 08"
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"


def glyph(ch: str) -> list[int]:
    big = 8
    img = Image.new("L", (W * big, H * big), 0)
    d = ImageDraw.Draw(img)
    f = ImageFont.truetype(FONT, int(H * big * 0.78))
    box = d.textbbox((0, 0), "0", font=f)
    x = (W * big - (box[2] - box[0])) / 2 - box[0]
    y = (H * big - (box[3] - box[1])) / 2 - box[1]
    d.text((x, y), ch, fill=255, font=f)
    small = img.resize((W, H), Image.Resampling.BOX)
    return [round(v / 255 * 15) for v in small.tobytes()]


def main() -> None:
    glyphs = [(c, glyph(c)) for c in CHARS if c != " "]
    glyphs.sort(key=lambda g: sum(g[1]))
    words: list[int] = []
    for _, px in glyphs:
        for i in range(0, len(px), 8):
            w = 0
            for k, v in enumerate(px[i : i + 8]):
                w |= v << (4 * k)
            words.append(w)
    per = W * H // 8
    print(f"// generated by tools/toys/printer_glyphs.py: {''.join(c for c, _ in glyphs)} (lightest first)")
    print(f"const TYPE_W: i32 = {W};\nconst TYPE_H: i32 = {H};\nconst TYPE_N: i32 = {len(glyphs)};")
    print(f"const TYPE_WORDS: i32 = {per};")
    print(f"const TYPE: array<u32, {len(words)}> = array<u32, {len(words)}>(")
    for i in range(0, len(words), 8):
        print("  " + ", ".join(f"0x{w:08x}u" for w in words[i : i + 8]) + ",")
    print(");")
    inks = [sum(px) / (15 * W * H) for _, px in glyphs]
    print(f"const INK: array<f32, {len(inks)}> = array<f32, {len(inks)}>(" + ", ".join(f"{v:.3f}" for v in inks) + ");")


if __name__ == "__main__":
    main()
