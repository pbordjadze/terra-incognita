#!/usr/bin/env python3
"""Bake the Cannae ground for the ink-orders spike into terrain.js.

Run: python3 build_terrain.py   (fetches Terrarium z13 tiles into ./.tiles, writes terrain.js)

Terrarium elevation (Mapzen/AWS open data, elevation = R*256+G+B/256-32768 m) around 41.30 N
16.13 E. The Aufidus (Ofanto) is traced as the cheapest path along the valley floor on smoothed
elevation (the tiles are too coarse to show the channel itself). The frame is turned so the river
runs down the left of the screen, the Romans' right as they face down-screen, Cannae's ridge on
the right: the deployment the sources describe, on the real ground.
"""
import heapq, json, math, os, urllib.request
import numpy as np
from PIL import Image
from scipy import ndimage

HERE = os.path.dirname(os.path.abspath(__file__))
TILES = os.path.join(HERE, '.tiles')
Z, X0, Y0, N = 13, 4461, 3060, 5
W, H, CELL = 1376, 1032, 8          # the field in CSS px, grid cell size
XF0 = -240                          # the grid reaches this far left of the field (the far bank, seen when the view is shifted)
MPP = 40075016 * math.cos(math.radians(41.3)) / (256 * 2 ** Z)   # metres per tile pixel


def mosaic():
    os.makedirs(TILES, exist_ok=True)
    rows = []
    for y in range(Y0, Y0 + N):
        r = []
        for x in range(X0, X0 + N):
            p = os.path.join(TILES, f'{Z}_{x}_{y}.png')
            if not os.path.exists(p):
                urllib.request.urlretrieve(
                    f'https://s3.amazonaws.com/elevation-tiles-prod/terrarium/{Z}/{x}/{y}.png', p)
            a = np.asarray(Image.open(p).convert('RGB')).astype(float)
            r.append(a[..., 0] * 256 + a[..., 1] + a[..., 2] / 256 - 32768)
        rows.append(np.hstack(r))
    return np.vstack(rows)


def thalweg(E, a, b):
    S = ndimage.gaussian_filter(E, 6)
    cost = np.maximum(S - S.min(), 0) ** 2 + 1.0
    h, w = E.shape
    dist = np.full(E.shape, np.inf); prev = {}
    dist[a[1], a[0]] = 0; q = [(0, a)]
    while q:
        d, (x, y) = heapq.heappop(q)
        if (x, y) == b: break
        if d > dist[y, x]: continue
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                if not dx and not dy: continue
                nx, ny = x + dx, y + dy
                if 0 <= nx < w and 0 <= ny < h:
                    nd = d + cost[ny, nx] * math.hypot(dx, dy)
                    if nd < dist[ny, nx]:
                        dist[ny, nx] = nd; prev[(nx, ny)] = (x, y); heapq.heappush(q, (nd, (nx, ny)))
    path = [b]
    while path[-1] != a: path.append(prev[path[-1]])
    p = np.array(path[::-1], float)
    # smooth, then thin
    p = np.stack([ndimage.gaussian_filter1d(p[:, 0], 8, mode='nearest'),
                  ndimage.gaussian_filter1d(p[:, 1], 8, mode='nearest')], 1)
    return p[::4]


def main():
    E = mosaic()
    river = thalweg(E, (120, 900), (1100, 230))
    # the valley's axis, and a frame across it
    ang = math.atan2(river[-1, 1] - river[0, 1], river[-1, 0] - river[0, 0])
    rot = -math.pi / 2 - ang          # the downstream direction points up the screen
    scale = 5200 / MPP / W            # tile px per screen px: ~5.2 km across
    # place the river ~16% in from the left at mid-height, nearest Cannae
    cannae = np.array([650.5, 628.5])   # Canne della Battaglia, 41.2958 N 16.1517 E
    d = np.linalg.norm(river - cannae, axis=1); rc = river[np.argmin(d)]
    c, s = math.cos(-rot), math.sin(-rot)

    def to_tile(sx, sy):              # screen px -> tile px
        u = (sx - W * 0.16) * scale; v = (sy - H * 0.5) * scale
        return rc[0] + c * u - s * v, rc[1] + s * u + c * v

    gw, gh = (W - XF0) // CELL + 1, H // CELL + 1
    ys, xs = np.mgrid[0:gh, 0:gw]
    tx, ty = to_tile(xs * CELL + XF0, ys * CELL)
    elev = ndimage.map_coordinates(ndimage.gaussian_filter(E, 1.5), [ty, tx], order=1)
    ci, si = math.cos(rot), math.sin(rot)
    rs = []
    for x, y in river:
        dx, dy = x - rc[0], y - rc[1]
        u = ci * dx - si * dy; v = si * dx + ci * dy
        rs.append([round(u / scale + W * 0.16, 1), round(v / scale + H * 0.5, 1)])
    cs = cannae - rc
    cx = (ci * cs[0] - si * cs[1]) / scale + W * 0.16; cy = (si * cs[0] + ci * cs[1]) / scale + H * 0.5
    out = dict(w=gw, h=gh, cell=CELL, x0=XF0, mpp=round(scale * MPP, 3),
               elev=[round(float(v), 1) for v in elev.ravel()], river=rs, cannae=[round(cx), round(cy)])
    with open(os.path.join(HERE, 'terrain.js'), 'w') as f:
        f.write('// Generated by build_terrain.py from Terrarium elevation; do not edit.\n')
        f.write('window.TERRAIN=' + json.dumps(out, separators=(',', ':')) + ';\n')
    print('grid', gw, gh, 'elev', elev.min(), elev.max(), 'm/px', scale * MPP, 'cannae', cx, cy)


if __name__ == '__main__':
    main()
